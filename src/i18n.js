export const DICTS = { en, es };

export function makeT(lang) {
  const dict = DICTS[lang] ?? en;
  return (key, vars = {}) => {
    const s = dict[key] ?? en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  };
}

/** Amounts: en "€1,234.56", es "1.234,56 €". */
export function formatMoney(cents, lang) {
  const sign = cents < 0 ? '-' : '';
  const abs = Math.abs(Math.round(cents));
  const [thou, dec] = lang === 'es' ? ['.', ','] : [',', '.'];
  const euros = Math.floor(abs / 100).toString().replace(/\B(?=(\d{3})+(?!\d))/g, thou);
  const n = `${euros}${dec}${String(abs % 100).padStart(2, '0')}`;
  return lang === 'es' ? `${sign}${n} €` : `${sign}€${n}`;
}

/** Plain numbers (kWh, readings, percentages): es uses a decimal comma. */
export function formatNumber(n, lang, digits) {
  if (n == null || !Number.isFinite(Number(n))) return '—';
  const v = digits != null ? Number(n).toFixed(digits) : String(Math.round(Number(n) * 1000) / 1000);
  return lang === 'es' ? v.replace('.', ',') : v;
}

/** Pick the language: saved preference, else the browser's Accept-Language, else English. */
export function pickLang(saved, acceptLanguage = '') {
  if (LANGS.includes(saved)) return saved;
  const first = String(acceptLanguage).split(',').map((p) => p.trim().slice(0, 2).toLowerCase()).find((l) => LANGS.includes(l));
  return first ?? 'en';
}
